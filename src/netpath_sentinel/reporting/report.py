import html
import json
import os
import tempfile
from pathlib import Path
from typing import Any


def export_json(path: Path, payload: dict[str, Any], sanitize: bool = True) -> Path:
    data = _redact(payload) if sanitize else payload
    _write_private(path, json.dumps(data, indent=2, default=str))
    return path


def export_html(
    path: Path,
    title: str,
    payload: dict[str, Any],
    report_kind: str = "technical",
) -> Path:
    payload = _redact(payload)
    if report_kind not in {"executive", "technical"}:
        raise ValueError("report_kind must be 'executive' or 'technical'")
    metrics = payload.get("metrics", {})
    findings = payload.get("findings", [])
    steps = payload.get("steps", [])
    summary = _executive_summary(payload, findings)
    metric_cards = "".join(
        "<article class='metric'><span>" + html.escape(label) + "</span><strong>"
        + html.escape(str(metrics.get(key, 0))) + "</strong></article>"
        for key, label in (
            ("tcp_sessions", "TCP sessions"),
            ("packets_observed", "Packets observed"),
            ("retransmissions", "Retransmissions"),
            ("findings", "Findings"),
        )
    )
    finding_cards = "".join(_finding_card(item) for item in findings)
    step_rows = "".join(_step_row(item) for item in steps)
    if report_kind == "executive":
        body = (
            f"{_technical_section('Scope', payload.get('configuration'))}"
            f"<section class='summary'><h2>Overall observed outcome</h2><p>{html.escape(summary)}</p></section>"
            f"<section><h2>Key metrics</h2><div class='metrics'>{metric_cards}</div></section>"
            f"<section><h2>Diagnostic steps</h2>{step_rows or '<p>No step details were stored.</p>'}</section>"
            f"<section><h2>Findings and next actions</h2>{finding_cards or '<p>No root cause finding was supported by the available evidence.</p>'}</section>"
            f"{_limitations(payload)}"
        )
    else:
        body = "".join(
            _technical_section(label, payload.get(key))
            for key, label in (
                ("configuration", "Diagnostic scope"),
                ("hostname", "Host"),
                ("os", "Operating system"),
                ("interfaces", "Interfaces"),
                ("routes", "Routes"),
                ("route_error", "Route collection status"),
                ("listeners", "Listening sockets"),
                ("metrics", "Capture metrics"),
                ("tcp_sessions", "TCP sessions and sequence state"),
                ("packet_timeline", "Packet timeline"),
                ("steps", "Diagnostic steps"),
                ("findings", "RCA findings"),
                ("evidence", "Evidence references"),
                ("limitations", "Capture limitations"),
            )
        )
    eyebrow = "Executive report" if report_kind == "executive" else "Technical report"
    _write_private(
        path,
        "<!doctype html><html lang='en'><head><meta charset='utf-8'>"
        "<meta name='viewport' content='width=device-width,initial-scale=1'>"
        f"<title>{html.escape(title)}</title><style>{_REPORT_CSS}</style></head>"
        f"<body><main><header><p class='eyebrow'>{eyebrow}</p>"
        f"<h1>{html.escape(title)}</h1><p class='muted'>Session {html.escape(str(payload.get('session_id', 'unknown')))}</p></header>"
        f"{body}<footer>Generated by NetPath Sentinel. Findings describe the evidence collected at this host and capture point.</footer></main></body></html>",
    )
    return path


def _executive_summary(payload: dict[str, Any], findings: Any) -> str:
    if isinstance(findings, list) and findings:
        first = findings[0]
        if isinstance(first, dict):
            return str(first.get("conclusion", "Diagnostic completed with recorded findings."))
    metrics = payload.get("metrics", {})
    packet_count = metrics.get("packets_observed", 0) if isinstance(metrics, dict) else 0
    return f"The diagnostic completed and observed {packet_count} matching TCP packets. No confirmed root cause was supported by the recorded findings."


def _finding_card(item: Any) -> str:
    if not isinstance(item, dict):
        return f"<article class='finding'><pre>{html.escape(str(item))}</pre></article>"
    fields = (
        ("Confidence", item.get("confidence")),
        ("Evidence references", item.get("supporting_evidence_ids", [])),
        ("Alternatives", item.get("alternatives", [])),
        ("Limitations", item.get("limitations", [])),
        ("Recommended verification", item.get("recommended_verification")),
        ("Next action", item.get("next_action")),
    )
    details = "".join(
        f"<p><strong>{html.escape(label)}:</strong> {html.escape(str(value))}</p>"
        for label, value in fields
        if value
    )
    return (
        "<article class='finding'><p class='eyebrow'>"
        + html.escape(str(item.get("code", "Finding")))
        + " | "
        + html.escape(str(item.get("severity", "info")))
        + "</p><h3>"
        + html.escape(str(item.get("conclusion", "")))
        + "</h3>"
        + details
        + "</article>"
    )


def _step_row(item: Any) -> str:
    if not isinstance(item, dict):
        return f"<details><summary>{html.escape(str(item))}</summary></details>"
    title = html.escape(str(item.get("name", item.get("step_id", "Step"))))
    status = html.escape(str(item.get("status", "unknown")))
    detail = {
        key: value
        for key, value in item.items()
        if key not in {"name", "step_id", "status", "id", "session_id"}
    }
    return (
        f"<details><summary><strong>{title}</strong><span class='badge'>{status}</span></summary>"
        f"<pre>{html.escape(json.dumps(detail, indent=2, default=str))}</pre></details>"
    )


def _technical_section(title: str, value: Any) -> str:
    if value in (None, [], {}):
        return ""
    return (
        f"<section><h2>{html.escape(title)}</h2><pre>"
        f"{html.escape(json.dumps(value, indent=2, default=str))}</pre></section>"
    )


def _limitations(payload: dict[str, Any]) -> str:
    value = payload.get("limitations", [])
    if not value:
        return ""
    items = "".join(f"<li>{html.escape(str(item))}</li>" for item in value)
    return f"<section><h2>Limitations</h2><ul>{items}</ul></section>"


